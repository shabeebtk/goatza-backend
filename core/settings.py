def env_list(name, default=""):
    """Read a comma-separated env var into a list of trimmed, non-empty items.

    Hosts and origins differ per environment, so they live in the environment
    rather than in this file. An unset or blank var falls back to `default`.
    """
    raw = os.getenv(name) or default
    return [item.strip() for item in raw.split(",") if item.strip()]

