# ------ RECRUITMENT APPLICANT ALERTS ------/
# How often an organization may be emailed about new applicants, by how many
# applications the recruitment has in total. Early applications feel instant;
# a recruitment that goes viral gets batched instead of one mail per applicant.
#
# (max_total_applications, min_seconds_since_last_alert), evaluated TOP-DOWN —
# the first tier whose bound the count fits under wins. None = no upper bound.
#
# The gap is measured from the last alert EMAIL, not the last application:
# measuring from the application would let a steady trickle re-arm the timer
# forever and never batch anything. Applications that arrive inside a gap are
# not dropped — they are counted into the next alert's "and N more".
#
# Tune freely; recruitments/services/applicant_alert_service.py reads this and
# hardcodes nothing.
APPLICANT_ALERT_TIERS = [
    (3, 0),        # applicants 1-3: alert instantly
    (7, 3600),     # applicants 4-7: at most one alert per hour
    (None, 14400), # applicants 8+ : at most one alert per 4 hours
]

# ------ GOOGLE PLACES (city + venue search) ------/
# The proxy in places/ is the ONLY thing that talks to Google. The key is
# server-side and never reaches the browser (docs/PLACES_MIGRATION.md decision
# 2), which is the whole reason the proxy exists.

# Unset is a supported state: the app boots normally and the two /places/
# endpoints answer 503 with a logged warning, so a checkout with no key still
# runs everything that is not place search.
GOOGLE_PLACES_API_KEY = os.getenv("GOOGLE_PLACES_API_KEY")

# The INNER spend backstop, per UTC day, per SKU. Google console quotas are the
# outer one — this is the one that can answer with a friendly 503 instead of a
# dead picker, and it stops the call before it is billed. `or` rather than
# getenv's default argument for the same reason as the R2 block above: the keys
# ship in .env with empty values, and int("") raises at import, which would
# take the whole app down over a blank line in an env file.
#
# Details and the coordinate-refresh job SHARE the details cap: same endpoint,
# same SKU, same money.
PLACES_DAILY_CAP_AUTOCOMPLETE = int(
    os.getenv("PLACES_DAILY_CAP_AUTOCOMPLETE") or 2000
)
PLACES_DAILY_CAP_DETAILS = int(os.getenv("PLACES_DAILY_CAP_DETAILS") or 1000)

# The city picker's type filter, comma-separated. A SETTING rather than a
# constant because which small towns Google classifies as a "city" is not
# stable and widening the list must not need a deploy.
#
# Google allows at most FIVE values here and refuses to mix a collection like
# `(cities)` with individual types, so this is a five-slot budget and every
# slot has to earn its place. `(cities)` used to hold the whole budget in one
# value (= locality + administrative_area_level_3), which covers Kannur and
# Thalassery and misses the panchayats underneath them — Panoor, Kadavathoor —
# which is most of the district. Spending the five slots individually buys
# those back:
#
#   locality                      towns and cities (Kannur)
#   administrative_area_level_3   taluks / municipalities (Thalassery)
#   administrative_area_level_4   panchayats and villages (Kadavathoor)
#   sublocality_level_1           named quarters of a larger town
#   postal_town                   the postal-area label some places carry
#                                 INSTEAD of a locality
#
# DELIBERATELY ABSENT: street_address, premise, subpremise, route and
# postal_code. Those are the doorstep, and a sports profile needs the town —
# nobody's exact whereabouts is part of playing football. The picker asks for
# these five; accounts' profile serializer refuses anything that is not a
# `city` so a crafted request cannot post a doorstep either.
PLACES_CITY_PRIMARY_TYPES = os.getenv("PLACES_CITY_PRIMARY_TYPES") or (
    "locality,"
    "administrative_area_level_3,"
    "administrative_area_level_4,"
    "sublocality_level_1,"
    "postal_town"
)

# ---- Coordinate lifecycle ("B-lite", doc section 6) ----
# We may keep a place_id forever but not its coordinates, so a Location's point
# is a cache with an expiry. REFRESH re-fetches a place something still depends
# on; EXPIRE nulls the coordinates of one nothing does. The gap between the two
# is the safety margin: refresh at 25 days so a place has five days of runs to
# be caught before the 30-day expiry drops it.
PLACES_COORDS_REFRESH_AFTER_DAYS = int(
    os.getenv("PLACES_COORDS_REFRESH_AFTER_DAYS") or 25
)
PLACES_COORDS_EXPIRE_AFTER_DAYS = int(
    os.getenv("PLACES_COORDS_EXPIRE_AFTER_DAYS") or 30
)

# What counts as an "active user" for the refresh job: last_login OR
# profile.updated_at inside this window. Both, because refresh tokens rotate
# for thirty days without touching last_login.
PLACES_ACTIVE_USER_DAYS = int(os.getenv("PLACES_ACTIVE_USER_DAYS") or 30)
# ------ GOOGLE PLACES END ------/

# ------ LOGGING ------/
# One console handler on stdout: Render captures a process's stdout as its log
# stream, and locally it is just the terminal. No file handler — a container's
# filesystem is ephemeral and nothing would ever read it.
#
# The app loggers (logging.getLogger(__name__) across accounts/, posts/,
# services/, utils/ ...) are deliberately NOT listed: they inherit the root
# logger, so every existing call starts emitting without a per-app entry here.
#
# That inheritance is what routes utils.emails to the console at WARNING and
# ERROR — the failed-attempt and permanently-lost-email lines. LOG_LEVEL may be
# raised to WARNING to quiet a noisy environment; it must never be set above
# ERROR, or a lost OTP stops being recorded anywhere at all.
LOGGING = {
    "version": 1,
    # False, so anything configured before this dict is read (Django's own
    # bootstrap loggers, a library's) keeps working instead of going silent.
    "disable_existing_loggers": False,
    "formatters": {
        "standard": {
            "format": "{levelname} {asctime} {name} {message}",
            "style": "{",
        },
    },
    "handlers": {
        "console": {
            "class": "logging.StreamHandler",
            "stream": sys.stdout,
            "formatter": "standard",
        },
    },
    "root": {
        "handlers": ["console"],
        "level": os.getenv("LOG_LEVEL", "INFO"),
    },
    "loggers": {
        # Framework chatter at INFO regardless of how loud LOG_LEVEL is set.
        "django": {
            "handlers": ["console"],
            "level": "INFO",
            "propagate": False,
        },
        # 4xx/5xx only. At INFO this logs a line for every handled request.
        "django.request": {
            "handlers": ["console"],
            "level": "WARNING",
            "propagate": False,
        },
        # The runserver access log. Kept at INFO so local development still
        # shows the familiar "GET /api/... 200" lines; in production gunicorn
        # or daphne does the access logging and this logger stays quiet.
        "django.server": {
            "handlers": ["console"],
            "level": "INFO",
            "propagate": False,
        },
    },
}
# ------ LOGGING END ------/


# ------ SENTRY (error reporting) ------/
# Guarded on the DSN, not on IS_PROD: unset means nothing initializes, which is
# the normal state on localhost and in CI. Setting the DSN in a staging
# environment is enough to turn it on there.
SENTRY_DSN = os.getenv("SENTRY_DSN")
if SENTRY_DSN:
    import sentry_sdk

    _sentry_options = {
        "dsn": SENTRY_DSN,
        # Performance tracing off by default — it is sampled per transaction
        # and the free tier's quota is spent on errors, not traces.
        "traces_sample_rate": float(os.getenv("SENTRY_TRACES_SAMPLE_RATE") or 0.0),
        # No emails, usernames or IPs attached to events. This app's users are
        # athletes, many of them minors; an error report is not a place for
        # their identifiers.
        "send_default_pii": False,
        "environment": "production" if IS_PROD else "development",
    }

    # Render injects the deployed commit SHA. With it, an issue points at the
    # exact code that raised instead of "whatever was live at the time".
    _sentry_release = os.getenv("RENDER_GIT_COMMIT")
    if _sentry_release:
        _sentry_options["release"] = _sentry_release

    sentry_sdk.init(**_sentry_options)
# ------ SENTRY END ------/
